import next from 'eslint-config-next';
import nextTypescript from 'eslint-config-next/typescript';

/**
 * There was no lint gate at all (#466).
 *
 * `package.json` carried `"lint": "next lint"`, a command Next.js 16 removed, so the script had
 * been failing since the upgrade — and nothing called it: `ci.yml`'s web job runs install, Vitest,
 * build and e2e, and never lint. The root `CLAUDE.md` listed lint among the quality gates all the
 * same. A gate that nobody runs is a comment.
 *
 * What this configuration is, deliberately: Next's own rules, nothing invented on top. The point
 * of the first pass is to have a gate that holds, not to impose a style on a codebase that has
 * been written for a year without one. Rules worth adding are worth adding later, one at a time,
 * with the fixes in the same change.
 */
export default [
  {
    ignores: [
      '.next/**',
      'node_modules/**',
      'out/**',
      'coverage/**',
      'playwright-report/**',
      'test-results/**',
      // Generated, and regenerated by their scripts rather than edited.
      'lib/yearPhotos.ts',
      'next-env.d.ts',
      // Not ours, and not TypeScript: the design ground truth is a self-contained prototype.
      'hivepulse-redesign/**',
      // A local working copy of the design-system bundle, not tracked by git at all. It carries a
      // vendored React build, which alone accounted for 1194 of the first run's 1602 findings.
      'ds-bundle/**',
      // The other platforms have their own toolchains.
      'android/**',
      'ios/**',
      'backend/**',
    ],
  },
  ...next,
  ...nextTypescript,
  {
    rules: {
      /**
       * Off, and not as a shortcut.
       *
       * The rule wants `'` written as `&apos;` inside JSX text. It exists to catch a quote that
       * accidentally ends an attribute, which TypeScript and the build already catch here. What it
       * actually finds in this repository is French: `l'application`, `qu'il`, `d'une` — 281 of
       * them in the help pages alone, every one of which React renders correctly. Five languages
       * of prose live in JSX, and asking each apostrophe to be an entity would make that prose
       * harder to read and to translate than the rule is worth.
       */
      'react/no-unescaped-entities': 'off',

      /**
       * Warnings, not errors, and deliberately so: these are a real backlog, written down rather
       * than switched off (#472).
       *
       * They come from React's newer compiler-aware rules, which this codebase has never been
       * held to. `set-state-in-effect` alone accounts for thirteen, and every one of them is the
       * ordinary data-fetching shape — `setLoading(true)` and then a fetch inside an effect. That
       * is not a bug; it is a render more than React would like, and straightening it out means
       * reworking how pages load, which is a refactor and not a tidy-up.
       *
       * One of them was a genuine finding and is fixed rather than demoted: `immutability` caught
       * `YearFeedback` writing to a variable from inside a `.map()` during render.
       */
      'react-hooks/set-state-in-effect': 'warn',
      'react-hooks/purity': 'warn',
      'react-hooks/refs': 'warn',
      'react-hooks/immutability': 'warn',

      /**
       * The six of these are Leaflet: a map library loaded dynamically, whose handles have no
       * useful type at the point they are held. Typing them properly is worth doing and is not
       * what a first lint pass is for (#472).
       */
      '@typescript-eslint/no-explicit-any': 'warn',
    },
  },
];
